// Форматирование чисел статистики — одна формула на build и runtime.
// Потребители: OfferStats.astro (финальное значение в HTML) и
// stats-counter.ts (промежуточные кадры набегания). Формула обязана быть
// общей: разъедутся варианты — цифра «дёрнется» в момент финиша, когда
// JS-значение сменится вёрсточным.
//
// Разделитель разрядов — НЕРАЗРЫВНЫЙ пробел (U+00A0): с обычным «13 000»
// ломается на две строки в узкой карточке.

export const formatStatNumber = (n: number): string =>
  String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
